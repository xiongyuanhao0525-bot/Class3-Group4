# 支持的环境变量：
#   - DJANGO_ELASTICSEARCH_HOST: ES主机地址（必需）
#   - ELASTICSEARCH_VERIFY_CERTS: 是否验证证书 (True/False)
#   - ELASTICSEARCH_USERNAME: 用户名
