        # 这些外键本身多是 CASCADE（级联删除）能自动兜底，显式排好序只是更直观。
        # 坑：Article.objects.all().delete() 删的是“全站文章”，
        #     并不只删上一次本命令造的那几篇 —— 所以它天然不适合正式库。
        # 清空旧数据
