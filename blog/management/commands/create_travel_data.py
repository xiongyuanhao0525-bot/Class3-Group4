        # 能用文章数据里写的字符串（如 '国内游'）直接取到分类对象：categories[data['category']]。
        # 坑：这里用的是 create() 而不是 get_or_create()。
        #     Category.name 有 unique=True，若第一步没清空就重复执行，第二次会因唯一约束报错；
